import { h, icon, countUp, fmt } from "../ui.js";
import { api } from "../api.js";
import { Board } from "../board.js";

const FEATURES = [
  ["play", "Classic and advanced rules", "Three board sizes, blocked cells, Pop Out, Remove Opponent and Heavy Piece, all enforced by your Python engine."],
  ["cpu", "Minimax vs Alpha-Beta", "Play the computer or watch two AIs play. See the move, time, nodes visited and branches pruned for every decision."],
  ["tree", "See the search", "Expand a real search tree node by node and watch Alpha-Beta cut branches that Minimax would explore."],
  ["chart", "Measured analytics", "A dashboard built from benchmark CSVs: KPIs, charts, statistics, filters and insights computed with pandas."],
];
const STACK = [
  ["Python engine", "Board, gravity, power-ups, Minimax and Alpha-Beta from the original project."],
  ["FastAPI", "REST API that exposes the engine, search, benchmarks and analytics."],
  ["pandas + NumPy", "Cleaning, statistics, correlations and generated insights."],
  ["HTML, CSS, JavaScript", "No build step and no Node.js: the site is served directly by FastAPI."],
];

export async function mount(root) {
  let alive = true, timer = 0;
  const board = h("div", { class: "hero-board" });
  const caption = h("div", { class: "hero-caption" });
  const stats = h("div", { class: "stat-strip" });
  root.append(
    h("section", { class: "hero" },
      h("div", {},
        h("h1", {}, "CONNECT 4 ", h("span", { class: "grad" }, "AI")),
        h("p", { class: "sub" }, "Intelligent Gaming Meets Data Science"),
        h("p", { class: "intro" }, "A Connect 4 game with a real search engine behind it. Play against Minimax or Alpha-Beta Pruning, then open the analytics to see how much work pruning saves, measured on 30 benchmark positions."),
        h("div", { class: "cta" },
          h("a", { class: "btn primary lg", href: "#/play", html: `${icon("play", 18)} Play Game` }),
          h("a", { class: "btn lg", href: "#/dashboard", html: `${icon("chart", 18)} Explore AI Dashboard` }))),
      h("div", { class: "glass card" }, board, caption)),
    h("section", { class: "section" }, h("h2", {}, "What you can do here"), h("p", { class: "lead" }, "Everything on this site runs on the original Connect 4 code. The browser only draws it."),
      h("div", { class: "features" }, FEATURES.map(([i, t, d]) => h("div", { class: "feature glass" }, h("div", { class: "fi", html: icon(i, 22) }), h("h3", {}, t), h("p", {}, d))))),
    h("section", { class: "section" }, h("h2", {}, "Benchmark results at a glance"), h("p", { class: "lead" }, "Live numbers from the shipped benchmark, not placeholders."), stats),
    h("section", { class: "section" }, h("h2", {}, "How it is built"), h("p", { class: "lead" }, "Python does the thinking. The website is plain web technology."),
      h("div", { class: "stack-list" }, STACK.map(([t, d]) => h("div", { class: "tech glass" }, h("b", {}, t), h("p", {}, d))))),
    h("footer", { class: "foot" }, "Connect 4 AI & Data Science · Minimax, Alpha-Beta Pruning and measured analytics."));

  // Hero: replay of a real AI-vs-AI game generated by the Python engine.
  const hb = new Board(board);
  async function play(seed) {
    if (!alive) return;
    let g;
    try { g = await api.demo(seed); } catch { caption.textContent = "Start the backend to see the live demo game."; return; }
    const st = { rows: g.rows, columns: g.columns, board: Array.from({ length: g.rows }, () => Array(g.columns).fill(0)), blocked_cells: [], winning_positions: [], current_player: 1, terminal: true };
    hb.reset(); hb.update(st, { locked: true });
    caption.textContent = "Alpha-Beta vs Alpha-Beta · replayed from the Python engine";
    let i = 0;
    const step = () => {
      if (!alive) return;
      if (i < g.moves.length) {
        const m = g.moves[i++]; st.board[m.row][m.column] = m.player; st.current_player = 3 - m.player;
        hb.update(st, { locked: true }); timer = setTimeout(step, 520);
      } else {
        st.winning_positions = g.winning_positions; hb.update(st, { locked: true });
        caption.textContent = g.winner ? `${g.winner === 1 ? "Red" : "Yellow"} connects four in ${g.moves.length} moves` : "Draw";
        timer = setTimeout(() => play(seed + 1), 3200);
      }
    };
    timer = setTimeout(step, 600);
  }
  play(Math.floor(Math.random() * 500));

  api.kpis({}).then((k) => {
    const items = [[k.scenarios, 0, "", "benchmark scenarios"], [k.mean_nodes_reduced_pct, 1, "%", "fewer nodes with Alpha-Beta"], [k.mean_speedup_ratio, 1, "×", "average speedup"], [k.total_pruned_branches, 0, "", "branches pruned in total"]];
    stats.append(...items.map(([v, d, s, l]) => { const n = h("b", {}, "0"); countUp(n, v, { decimals: d, suffix: s }); return h("div", { class: "stat glass" }, n, h("span", {}, l)); }));
  }).catch(() => stats.append(h("p", { class: "muted" }, "Statistics appear once the backend is running.")));

  return () => { alive = false; clearTimeout(timer); };
}
